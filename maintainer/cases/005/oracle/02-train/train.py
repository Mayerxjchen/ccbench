#!/usr/bin/env python3
"""042 stage 2 — initial DPMP training (deepmd-jax).

Adapts public/dpmp-config/train.py to the labels generated by stage 1.
Uses named CLI arguments so data dirs, seed, and interface never collide:

    python train.py --steps 1000000 --data-dir ../work/train-round0 \\
                    --seed 42 [--interface graphene-water]

Each --data-dir must exist and be a DeepMD raw set (type.raw + set.*).  The
schedule is env-gated by the caller: smoke uses a handful of steps, formal
uses the paper's 1e6.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

from deepmd_jax.train import train


def _require_deepmd_set(path: Path) -> None:
    if not path.is_dir():
        print(f"[train] ERROR: data dir does not exist: {path}", file=sys.stderr)
        sys.exit(2)
    if not (path / "type.raw").is_file():
        print(f"[train] ERROR: not a DeepMD set (missing type.raw): {path}", file=sys.stderr)
        sys.exit(2)
    sets = sorted(path.glob("set.*"))
    if not sets:
        print(f"[train] ERROR: no set.* in data dir: {path}", file=sys.stderr)
        sys.exit(2)


def main() -> int:
    parser = argparse.ArgumentParser(description="042 stage-2 DPMP training")
    parser.add_argument("--steps", type=int, default=100,
                        help="training steps (smoke default 100; formal 1e6)")
    parser.add_argument("--data-dir", action="append", required=True,
                        dest="data_dirs",
                        help="DeepMD raw set dir (repeatable; at least one required)")
    parser.add_argument("--seed", type=int, default=None,
                        help="RNG seed (default: random)")
    parser.add_argument("--interface", default=None,
                        help="interface name, for provenance only")
    args = parser.parse_args()

    if not args.data_dirs:
        print("[train] ERROR: at least one --data-dir is required", file=sys.stderr)
        return 2
    for d in args.data_dirs:
        _require_deepmd_set(Path(d))

    seed = args.seed if args.seed is not None else int(np.random.randint(1, int(1e10)))

    train(
        model_type="energy",
        rcut=6.0,
        train_data_path=args.data_dirs,
        val_data_path=None,
        save_path="model.pkl",
        step=args.steps,
        mp=True,
        atomic_sel=None,
        embed_widths=[48, 48, 96],
        embed_mp_widths=[96, 96, 96],
        fit_widths=[96, 96, 96],
        axis_neurons=16,
        lr=0.001,
        batch_size=1,
        val_batch_size_ratio=0,
        compress=True,
        print_every=100,
        atomic_data_prefix="atomic_dipole",
        s_pref_e=0.02,
        l_pref_e=1,
        s_pref_f=1000,
        l_pref_f=1,
        lr_limit=1e-8,
        beta2=0.99,
        decay_steps=5000,
        getstat_bs=1,
        label_bs=1,
        tensor_2nd=True,
        print_loss_smoothing=20,
        compress_Ngrids=1024,
        compress_r_min=0.6,
        seed=seed,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
