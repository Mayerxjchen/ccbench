"""dftworld Target Adapter: render Builder case-designs into executable drafts.

Produces ``task.toml`` v1.2, a root ``Dockerfile``, ``.dockerignore`` and
``source/dftworld-target.lock.json``.  The adapter validates and renders the
approved design; it never guesses or changes the execution class and never
touches scientific content, reference, solution, tests, profiles or evidence.

Generated bytes are deterministic (no timestamps in any digest input).
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import jsonschema

from dftworld_bench.case_factory.state import (
    FactoryGates,
    LOCK_RELPATH,
    read_factory_state,
)
from dftworld_bench.case_factory.target import (
    GeneratedFile,
    SCHEMA_PATH,
    TargetVerdict,
)

IMAGE_SAFE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]*(:[A-Za-z0-9._-]+)?$")

# Substrings never allowed in a generated Dockerfile image reference.
_IMAGE_FORBIDDEN = ("$", "`", "\\", "&&", "||", ";", "|", ">", "<", "@", ":22",
                    "/home", "/root", "/public", ".ssh", ".sif", "http", "https")

# .dockerignore: private and build-irrelevant paths never enter the build context.
DOCKERIGNORE_ENTRIES = [
    "reference",
    "solution",
    "tests",
    "profiles",
    "evidence",
    "source",
    ".git",
    "jobs",
    "**/*.pem",
    "**/*.key",
    "**/*.p12",
    "**/*.jks",
    "**/id_rsa",
    "**/id_ed25519",
    "**/credentials",
    "**/.env",
    ".venv",
    "**/__pycache__",
    "**/*.pyc",
]


class RenderError(ValueError):
    """Raised when a design cannot be rendered into safe generated files."""


@dataclass
class DftworldTargetAdapter:
    """Repository-owned Target Adapter for dftworld."""

    name: str = "dftworld"
    version: str = "0.1.0"
    _schema: dict = field(default=None, repr=False)  # type: ignore[assignment]

    # -- TargetAdapter protocol ---------------------------------------------

    def validate_design(self, case_dir: Path, design: dict) -> TargetVerdict:
        errors = self._design_errors(design)
        return TargetVerdict(
            valid=not errors,
            errors=tuple(errors),
            gates=FactoryGates(design_valid=not errors),
        )

    def render(self, case_dir: Path, design: dict) -> tuple[GeneratedFile, ...]:
        errors = self._design_errors(design)
        if errors:
            raise RenderError("; ".join(errors))
        files = self._render_all(Path(case_dir), design)
        return tuple(files)

    def expected_output(
        self, case_dir: Path, design: dict
    ) -> tuple[GeneratedFile, ...]:
        """The committed expectation for an on-disk rendered case.

        The lock is recomputed from the gates recorded on disk, so both a
        freshly rendered lock (target_adapter_valid=false) and the CLI's
        committed lock (true) validate clean while any hand edit to a field the
        adapter renders — design, digests, adapter_version — shows up as drift.
        """
        case_dir = Path(case_dir)
        manifest = self._render_manifest(design)
        dockerfile = self._render_dockerfile(design)
        dockerignore = self._render_dockerignore(design)
        disk_gates = read_factory_state(case_dir)
        lock = self._render_lock(design, manifest, dockerfile, dockerignore, disk_gates)
        return (
            GeneratedFile(Path("task.toml"), manifest, _digest(manifest)),
            GeneratedFile(Path("Dockerfile"), dockerfile, _digest(dockerfile)),
            GeneratedFile(Path(".dockerignore"), dockerignore, _digest(dockerignore)),
            GeneratedFile(LOCK_RELPATH, lock, _digest(lock)),
        )

    def validate_output(self, case_dir: Path, design: dict) -> TargetVerdict:
        """Recompute expected bytes without writing and compare to disk.

        Returns target_adapter_valid=true only when every generated file exists
        on disk and its bytes match the recomputed expected bytes exactly.
        """
        errors: list[str] = []
        for gf in self.expected_output(case_dir, design):
            disk = Path(case_dir) / gf.path
            if not disk.is_file():
                errors.append(f"generated file missing on disk: {gf.path}")
                continue
            if disk.read_bytes() != gf.content:
                errors.append(f"generated file drifted from expected bytes: {gf.path}")
        return TargetVerdict(
            valid=not errors,
            errors=tuple(errors),
            gates=FactoryGates(
                design_valid=True,
                target_adapter_valid=not errors,
            ),
        )

    # -- rendering -----------------------------------------------------------

    def _design_errors(self, design: dict) -> list[str]:
        errors: list[str] = []
        schema = self._load_schema()
        raw_errors = sorted(
            jsonschema.Draft202012Validator(schema).iter_errors(design),
            key=lambda e: list(e.path),
        )
        for e in raw_errors:
            path = "/".join(str(p) for p in e.path) or "<root>"
            errors.append(f"{path}: {e.message}")

        image = ((design.get("runtime") or {}).get("candidate_image") or "")
        if image and not IMAGE_SAFE.fullmatch(image):
            errors.append(f"runtime.candidate_image unsafe: {image!r}")
        elif image and any(bad in image for bad in _IMAGE_FORBIDDEN):
            errors.append(f"runtime.candidate_image forbidden token: {image!r}")
        return sorted(set(errors))

    def _render_all(self, case_dir: Path, design: dict) -> list[GeneratedFile]:
        manifest = self._render_manifest(design)
        dockerfile = self._render_dockerfile(design)
        dockerignore = self._render_dockerignore(design)
        # Render may set design_valid + target_adapter_valid; runtime/smoke
        # gates persist from any existing lock and are never set by rendering.
        disk_gates = read_factory_state(case_dir)
        gates = FactoryGates(
            design_valid=True,
            target_adapter_valid=False,
            runtime_contract_valid=disk_gates.runtime_contract_valid,
            verifier_command_valid=disk_gates.verifier_command_valid,
            runtime_valid=disk_gates.runtime_valid,
            candidate_smoke_valid=disk_gates.candidate_smoke_valid,
        )
        lock = self._render_lock(design, manifest, dockerfile, dockerignore, gates)
        return [
            GeneratedFile(Path("task.toml"), manifest, _digest(manifest)),
            GeneratedFile(Path("Dockerfile"), dockerfile, _digest(dockerfile)),
            GeneratedFile(Path(".dockerignore"), dockerignore, _digest(dockerignore)),
            GeneratedFile(LOCK_RELPATH, lock, _digest(lock)),
        ]

    def commit_lock(
        self, design: dict, prior: FactoryGates
    ) -> GeneratedFile:
        """Build the committed lock marking target_adapter_valid=true.

        ``prior`` carries runtime/smoke gates from the real case (read BEFORE
        the lock is overwritten) so later independent checks never false-drift.
        """
        manifest = self._render_manifest(design)
        dockerfile = self._render_dockerfile(design)
        dockerignore = self._render_dockerignore(design)
        gates = FactoryGates(
            design_valid=True,
            target_adapter_valid=True,
            runtime_contract_valid=prior.runtime_contract_valid,
            verifier_command_valid=prior.verifier_command_valid,
            runtime_valid=prior.runtime_valid,
            candidate_smoke_valid=prior.candidate_smoke_valid,
        )
        lock = self._render_lock(design, manifest, dockerfile, dockerignore, gates)
        return GeneratedFile(LOCK_RELPATH, lock, _digest(lock))

    def _render_manifest(self, design: dict) -> bytes:
        identity = design["identity"]
        runtime = design["runtime"]
        execution = design["execution"]["class"]
        submission = design["submission"]
        candidate_files = design["candidate_files"]

        body: list[str] = []
        body.append('schema_version = "1.2"')
        body.append(f"case_version = {_toml_str(identity['case_version'])}")
        body.append("artifacts = []")
        body.append("")
        body.append("[execution]")
        body.append(f"class = {_toml_str(execution)}")
        body.append("")
        body.append("[candidate]")
        body.append('instruction = "instruction.md"')
        body.append(f"submission_root = {_toml_str(submission['root'])}")
        body.append("legacy_submission_layout = false")
        body.append(f"image = {_toml_str(runtime['candidate_image'])}")
        for rule in candidate_files:
            body.append("")
            body.append("[[candidate.files]]")
            body.append(f"source = {_toml_str(rule['source'])}")
            body.append(f"destination = {_toml_str(rule['destination'])}")
            if rule.get("strip_prefix"):
                body.append(f"strip_prefix = {_toml_str(rule['strip_prefix'])}")

        if execution == "hpc_controller":
            hpc = design["hpc"]
            body.append("")
            body.append("[hpc]")
            body.append(f"contract_version = {_toml_str(hpc['contract_version'])}")
            body.append(
                "required_capabilities = "
                + _toml_strlist(hpc["required_capabilities"])
            )
            # Three-layer runtime contract: scientific compute capabilities
            # separate platform capabilities (scheduler/gpu/fetch) from what
            # heavy science must/may run (cp2k fixed by the paper; DPMP
            # training / long JAX-MD placement is a Discovery decision).
            if hpc.get("scientific_capabilities"):
                sc = hpc["scientific_capabilities"]
                body.append("")
                body.append("[hpc.scientific_capabilities]")
                for key in ("required", "optional"):
                    if sc.get(key):
                        body.append(
                            f"{key} = " + _toml_strlist(sc[key])
                        )

        body.append("")
        body.append("[task]")
        body.append(f"name = {_toml_str(identity['task_name'])}")
        body.append(f"title = {_toml_str(identity['title'])}")
        body.append(f"description = {_toml_str(identity['description'])}")
        body.append("authors = []")
        body.append("keywords = []")
        body.append("")
        body.append("[metadata]")
        body.append("")
        body.append("[verifier]")
        body.append(f"timeout_sec = {_toml_number(runtime['verifier_timeout_sec'])}")
        body.append("")
        body.append("[verifier.env]")
        body.append("")
        body.append("[agent]")
        body.append(f"timeout_sec = {_toml_number(runtime['agent_timeout_sec'])}")
        body.append("")
        body.append("[environment]")
        body.append(f"build_timeout_sec = {_toml_number(runtime['build_timeout_sec'])}")
        body.append('os = "linux"')
        body.append(f"cpus = {_toml_number(runtime['cpus'])}")
        body.append(f"memory_mb = {_toml_number(runtime['memory_mb'])}")
        body.append(f"storage_mb = {_toml_number(runtime['storage_mb'])}")
        body.append(f"gpus = {_toml_number(runtime['gpus'])}")
        body.append(f"allow_internet = {_toml_bool(runtime['allow_internet'])}")
        body.append("mcp_servers = []")
        body.append("")
        body.append("[environment.env]")
        body.append("")
        body.append("[solution.env]")
        body.append("")
        body.append("[generated]")
        body.append(f"target = {_toml_str(self.name)}")
        body.append(f"adapter_version = {_toml_str(self.version)}")
        body.append(f"design_sha256 = {_toml_str(_design_digest(design))}")
        body.append("")
        text = "\n".join(body)
        _reject_control(text, "task.toml")
        return text.encode("utf-8")

    def _render_dockerfile(self, design: dict) -> bytes:
        image = design["runtime"]["candidate_image"]
        text = f"FROM {image}\nCOPY public/ /app/\n"
        _reject_control(text, "Dockerfile")
        return text.encode("utf-8")

    def _render_dockerignore(self, design: dict) -> bytes:
        lines = ["# generated by dftworld Case Factory; do not edit"]
        lines.extend(DOCKERIGNORE_ENTRIES)
        return ("\n".join(lines) + "\n").encode("utf-8")

    def _render_lock(
        self,
        design: dict,
        manifest: bytes,
        dockerfile: bytes,
        dockerignore: bytes,
        gates: FactoryGates,
    ) -> bytes:
        # The lock's own digest is recomputable from disk bytes and is NOT
        # self-referential; only the three sibling generated files are hashed.
        generated = {
            "task.toml": _digest(manifest),
            "Dockerfile": _digest(dockerfile),
            ".dockerignore": _digest(dockerignore),
        }
        payload = {
            "schema_version": "target-lock/v1",
            "target": self.name,
            "adapter_version": self.version,
            "case_id": design["identity"]["case_id"],
            "design_sha256": _design_digest(design),
            "generated_files": generated,
            "factory_gates": gates.as_dict(),
            "execution": design["execution"]["class"],
        }
        raw = json.dumps(payload, indent=2, sort_keys=True) + "\n"
        return raw.encode("utf-8")

    def _load_schema(self) -> dict:
        if self._schema is None:
            self._schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
        return self._schema


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #

def _design_digest(design: dict) -> str:
    canonical = json.dumps(design, sort_keys=True, separators=(",", ":"))
    return "sha256:" + hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _digest(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def _toml_str(value: str) -> str:
    if "\n" in value or "\r" in value or "\t" in value:
        raise RenderError(f"unsafe control character in TOML string: {value!r}")
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _toml_strlist(values: list[str]) -> str:
    return "[" + ", ".join(_toml_str(v) for v in values) + "]"


def _toml_number(value: Any) -> str:
    if isinstance(value, float):
        return str(value)
    return str(int(value))


def _toml_bool(value: bool) -> str:
    return "true" if value else "false"


def _reject_control(text: str, what: str) -> None:
    if any(ord(c) < 32 and c not in "\n\r\t" for c in text):
        raise RenderError(f"control character in {what}")
